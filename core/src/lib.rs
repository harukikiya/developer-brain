//! # Developer Brain Core
//!
//! VS Code 上で Markdown ドキュメント・ソースコード・用語集を、
//! **コードを理解する知識グラフ** として結ぶナレッジエンジンの中核です。
//!
//! このページ（と各型のドキュメント）は `cargo doc` で生成され、
//! GitHub Pages にそのまま公開されます。つまり **このコメント自体が
//! 公開仕様書** です。仕様を変えたいときはコメントを直してください。
//!
//! ## アーキテクチャ
//!
//! 主役はこの Rust コア（ヘッドレスな知識エンジン）です。
//! VS Code 拡張・MCP サーバ・CLI は、いずれもこのコアのクライアントに
//! すぎません。コアはエディタにも特定のプロトコルにも依存しません。
//!
//! ```text
//! クライアント:  VS Code 拡張(TS)   AI エージェント   CLI/CI
//!                     │ LSP             │ MCP           │
//!                     └─────────────────┴───────────────┘
//!                                  │
//!         ┌────────────────────────────────────────────┐
//!         │  dbrain-core（このクレート）= エンジン         │
//!         │  索引 / グラフ / リンク解決 / 用語集 / JSON 出力  │
//!         └────────────────────────────────────────────┘
//! ```
//!
//! この分離には理由があります。編集機能（補完・ジャンプ・Hover）を
//! 先に作りたくなっても、ロジックを VS Code 側（TypeScript）に書くと、
//! あとから MCP（AI 連携）を足すときに全部書き直しになります。
//! ロジックをコアに閉じ込めておけば、UI も AI も「同じ頭脳」を共有できます。
//!
//! ## 設計の核心: 「参照は座標ではなくクエリ」
//!
//! リンクには位置（行番号）を保存せず、シンボルの同一性
//! （[`SymbolDescriptor`]）だけを保存します。現在位置は索引のたびに
//! tree-sitter で解決し直します。詳しくは [`model`] モジュールを参照。
//!
//! この一手で、行ズレ耐性（人間）・壊れない参照ハンドル（AI）・
//! コンパクトな索引（メモリ）の 3 つが同時に手に入ります。
//!
//! ## モジュール構成
//!
//! - [`model`] … 全体の土台となるデータ型（ノード・辺・記述子・参照）。
//!   まずはここを読むのがおすすめです。
//! - [`index`] … ワークスペースを走査して知識グラフを組み立てる索引器（M1）。
//!
//! ## 開発ロードマップ
//!
//! - **M0（現在）** 足場とデータモデルの確定、参照パーサ。
//! - **M1** ファイル走査 → リンク抽出 + tree-sitter シンボル索引 →
//!   グラフ構築 → JSON 出力。
//! - **M2** LSP で `[[` 補完・リンクジャンプ・Hover。
//! - **M3** Webview のグラフビュー。
//! - **M4** 増分更新とファイル監視（非ブロック化）。
//! - **M5+** 陳腐化検出・用語集 Linter・MCP アダプタ。

